#!/usr/bin/env python3
"""Package the UI into one Apps Script file; never includes private settings."""
import json
from pathlib import Path
code = Path('Code.gs').read_text() + '\n' + Path('Website.gs').read_text() + '\n' + Path('BrowserFallback.gs').read_text()
old = "return HtmlService.createHtmlOutputFromFile('Index').setTitle('Job Application Notion Importer');"
assert old in code
for name in ('previewApplications', 'importApplications', 'previewWebsiteRows', 'fillWebsiteRows', 'previewBrowserFallback', 'fillBrowserFallback'):
    assert 'function ' + name + '(' in code, 'Missing backend function: ' + name
html = json.dumps(Path('Index.html').read_text(), ensure_ascii=False)
Path('SingleFile.gs').write_text('// Generated by scripts/build-single.py; edit Code.gs, Website.gs, BrowserFallback.gs and Index.html instead.\n' + code.replace(old, "return HtmlService.createHtmlOutput(" + html + ").setTitle('Job Application Notion Importer');"))
